//! Render pipeline: the path from Markdown source to an HTML fragment -
//! parsing, syntax-highlight splicing, sanitizing, title derivation, in
//! that order, sanitized once, after splicing - plus the single deep
//! workflow entry point (convert) that reads the source, renders, and
//! writes the page with per-worker private-output safeguards.

