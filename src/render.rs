/// Build a `file://` URL for a directory, suitable for use as `<base href>`.
///
/// Delegates to [`Url::from_directory_path`], which correctly
/// percent-encodes reserved and non-ASCII characters (spaces, `#`, `%`, `?`,
/// Unicode, …) and handles Windows drive letters, UNC paths, and the
/// `\\?\`/`\\?\UNC\` extended-length prefixes that `fs::canonicalize`
/// produces — a hand-rolled string transform got all of this subtly wrong
/// (e.g. a literal `#` in a directory name would truncate the URL when a
/// browser parsed it as a fragment). Always includes a trailing slash so
/// relative refs resolve correctly against the directory.
///
/// Returns `None` if `dir` can't be represented as a `file://` URL (notably:
/// relative paths). Callers should fall back to omitting the `<base href>`
/// tag entirely rather than emit a broken URL.
fn dir_to_file_url(dir: &Path) -> Option<String> {
    Url::from_directory_path(dir)
        .ok()
        .map(|url| url.to_string())
}

fn markdown_options() -> Options {
    let mut options = Options::empty();
    options.insert(Options::ENABLE_STRIKETHROUGH);
    options.insert(Options::ENABLE_TABLES);
    options.insert(Options::ENABLE_FOOTNOTES);
    options.insert(Options::ENABLE_TASKLISTS);
    options.insert(Options::ENABLE_GFM);

    options
}

fn markdown_to_html(
    markdown: &str,
    placeholder_discriminator: u64,
    plain_fences: &BTreeSet<usize>,
) -> highlight::RenderedMarkdown {
    // Front matter is stripped here, before parsing, by the same
    // `yaml_front_matter` splitter that title derivation uses, so one set of
    // acceptance rules governs both. Options::ENABLE_YAML_STYLE_METADATA_BLOCKS
    // is deliberately NOT enabled: pulldown-cmark 0.13 recognizes metadata
    // blocks anywhere at indent 0, not just at document start, which silently
    // swallows mid-document text framed by `---` lines.
    let markdown = yaml_front_matter(markdown)
        .map(|(_, body)| body)
        .unwrap_or(markdown);

    highlight::render(
        markdown,
        markdown_options(),
        placeholder_discriminator,
        plain_fences,
    )
}

/// Upper bound on placeholder-collision retries. A collision requires
/// document text that normalizes into the current placeholder token, so more
/// than a couple of retries only happens with adversarial input; past the cap
/// the document renders with highlighting disabled rather than looping.
const MAX_PLACEHOLDER_RETRIES: u32 = 16;

/// Shared render/process/splice loop behind [`safe_markdown_body`] and
/// [`convert`].
///
/// Highlighted spans are generated by mdo from escaped code text and spliced
/// into the raw renderer output only after all placeholders have been
/// validated. `process` (usually ammonia) then handles the completed document,
/// including generated markup, so no string insertion happens beyond the
/// sanitizer boundary. The loop is guaranteed to terminate:
///
/// - a destroyed placeholder can never survive under any discriminator, so
///   its fence is added to the strictly growing `plain_fences` set and
///   rendered as an ordinary escaped code block instead;
/// - collisions retry with a fresh discriminator at most
///   [`MAX_PLACEHOLDER_RETRIES`] times, after which every fence is rendered
///   plain, leaving nothing to splice.
fn spliced_markdown_body(
    markdown: &str,
    mut render: impl FnMut(&str, u64, &BTreeSet<usize>) -> highlight::RenderedMarkdown,
    mut process: impl FnMut(&str) -> String,
) -> (String, Option<&'static str>) {
    let mut discriminator = 0_u64;
    let mut collision_retries = 0_u32;
    let mut plain_fences = BTreeSet::new();

    loop {
        let rendered = render(markdown, discriminator, &plain_fences);
        match rendered.finish(rendered.raw_html().to_string()) {
            Ok(body) => return (process(&body), rendered.css()),
            Err(highlight::SpliceError::Destroyed(fences)) => {
                plain_fences.extend(fences);
            }
            Err(highlight::SpliceError::Collision) => {
                collision_retries += 1;
                if collision_retries > MAX_PLACEHOLDER_RETRIES {
                    plain_fences.extend(0..rendered.fence_count());
                }
                discriminator += 1;
            }
        }
    }
}

/// Render and sanitize Markdown, splicing generated highlighting before the
/// completed document crosses the sanitizer boundary.
fn safe_markdown_body(markdown: &str) -> (String, Option<&'static str>) {
    spliced_markdown_body(markdown, markdown_to_html, sanitize_html)
}

fn sanitize_html(html: &str) -> String {
    ammonia::Builder::default()
        // The global "class" allowance is intentional: user-authored class
        // names are inert here because classes only select styles from mdo's
        // own generated stylesheet. Highlight safety does not rest on this
        // allowlist either: highlighted markup is generated from escaped code
        // text, spliced before sanitization, and then cleaned with the rest of
        // the document.
        .add_generic_attributes(&["class", "id"])
        .add_tags(&["input"])
        .add_tag_attributes("input", &["checked", "type"])
        .add_tag_attribute_values("input", "checked", &[""])
        .add_tag_attribute_values("input", "type", &["checkbox"])
        .set_tag_attribute_value("input", "disabled", "")
        .clean(html)
        .to_string()
}

/// Render Markdown supplied in memory as a complete, self-contained HTML page.
///
/// This is the platform-neutral entry point used by the Android application.
/// Raw HTML is always sanitized, matching the safe default of the desktop CLI.
/// `fallback_title` is used only when the document has no top-level heading.
pub fn render_markdown_document(
    markdown: &str,
    fallback_title: &str,
    source_modified_unix_secs: Option<u64>,
) -> String {
    let (body, highlight_css) = safe_markdown_body(markdown);
    let title = derive_title(markdown, fallback_title);
    wrap_html5(
        &body,
        &title,
        None,
        None,
        highlight_css,
        source_modified_unix_secs,
    )
}

fn derive_title(markdown: &str, fallback: &str) -> String {
    if let Some(title) = front_matter_title(markdown) {
        return title;
    }

    // A valid metadata block is not document content. Exclude it from the
    // existing H1 search even when it has no usable title key.
    let markdown = yaml_front_matter(markdown)
        .map(|(_, document)| document)
        .unwrap_or(markdown);

    // Strip fenced code blocks first so a heading — whether an ATX `# ` line or
    // a raw <h1> — inside a ``` or ~~~ block is never mistaken for the title.
    let without_fences = strip_code_fences(markdown);
    for line in without_fences.lines() {
        let trimmed = line.trim_start();
        if let Some(rest) = trimmed.trim_end().strip_prefix("# ") {
            return rest.trim().to_string();
        }
    }
    if let Some(title) = derive_raw_html_h1_title(&without_fences) {
        return title;
    }
    fallback.to_string()
}

/// Extract a simple scalar `title:` from a complete YAML-style metadata block
/// at the start of the document.
///
/// pulldown-cmark deliberately recognizes the block delimiters without
/// interpreting YAML. mdo follows that narrow behavior: it reads only an
/// unindented `title` key and does not add a general-purpose YAML parser (and
/// its dependency/security surface) merely to title the generated page.
fn front_matter_title(markdown: &str) -> Option<String> {
    let (metadata, _) = yaml_front_matter(markdown)?;
    let mut title = None;
    for line in metadata.lines() {
        if line.starts_with(char::is_whitespace) {
            continue;
        }
        if let Some((key, value)) = line.split_once(':') {
            if key == "title" {
                let value = unquote_front_matter_scalar(value.trim());
                if !value.is_empty() {
                    title = Some(value.to_string());
                }
            }
        }
    }

    title
}

/// Split a complete YAML-style metadata block from the document body. The
/// returned metadata excludes delimiters.
///
/// This splitter is the single source of truth for front-matter recognition
/// (both hiding the block from rendered output and title extraction), and its
/// acceptance rules are deliberately conservative and GitHub-like:
///
/// - the opening `---` must be the very first line of the document;
/// - the closing delimiter is `---` or `...` on its own line — trailing
///   spaces are allowed but tabs are not;
/// - the block must be non-empty and its first line must not be blank.
///   GitHub and pulldown-cmark both reject blocks whose first content line is
///   blank, so treating them as front matter here would hide visible content
///   and let e.g. `---\n\ntitle: fake\n---` spoof the page title.
fn yaml_front_matter(markdown: &str) -> Option<(&str, &str)> {
    fn delimiter(line: &str) -> Option<&str> {
        let line = line.trim_end_matches(['\r', '\n']).trim_end_matches(' ');
        (line == "---" || line == "...").then_some(line)
    }

    let first_line_end = markdown.find('\n').unwrap_or(markdown.len());
    if delimiter(&markdown[..first_line_end]) != Some("---") || first_line_end == markdown.len() {
        return None;
    }

    let metadata_start = first_line_end + 1;
    let remainder = &markdown[metadata_start..];
    let mut consumed = 0;
    // split_inclusive also yields a final segment without a trailing newline,
    // so a closing delimiter at end-of-input is found by the loop as well.
    for segment in remainder.split_inclusive('\n') {
        if delimiter(segment).is_some() {
            let metadata = &remainder[..consumed];
            let first_content_line = metadata.lines().next()?;
            if first_content_line.trim().is_empty() {
                return None;
            }
            return Some((metadata, &remainder[consumed + segment.len()..]));
        }
        consumed += segment.len();
    }

    None
}

fn unquote_front_matter_scalar(value: &str) -> &str {
    if value.len() < 2 {
        return value;
    }

    let bytes = value.as_bytes();
    if matches!(
        (bytes[0], bytes[value.len() - 1]),
        (b'\'', b'\'') | (b'"', b'"')
    ) {
        &value[1..value.len() - 1]
    } else {
        value
    }
}

/// Return `markdown` with fenced code blocks (``` or ~~~) removed, so title
/// detection never reads inside code samples.
fn strip_code_fences(markdown: &str) -> String {
    let mut out = String::with_capacity(markdown.len());
    let mut fence: Option<char> = None;
    for line in markdown.lines() {
        if let Some(marker) = code_fence_marker(line.trim_start()) {
            match fence {
                Some(open) if open == marker => fence = None,
                Some(_) => {}
                None => fence = Some(marker),
            }
            continue;
        }
        if fence.is_some() {
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// Detect a code-fence line, returning its marker char when the line starts
/// with at least three backticks or tildes. This is a pragmatic subset of
/// CommonMark (it does not bound the indent or require the closing fence to be
/// at least as long), which is sufficient for title detection.
fn code_fence_marker(trimmed_start: &str) -> Option<char> {
    if trimmed_start.starts_with("```") {
        Some('`')
    } else if trimmed_start.starts_with("~~~") {
        Some('~')
    } else {
        None
    }
}

fn derive_raw_html_h1_title(markdown: &str) -> Option<String> {
    let lower = markdown.to_ascii_lowercase();
    let mut search_start = 0;

    while let Some(offset) = lower[search_start..].find("<h1") {
        let start = search_start + offset;
        let after_tag_name = start + 3;
        let next = lower.as_bytes().get(after_tag_name).copied();
        if !matches!(
            next,
            Some(b'>') | Some(b' ') | Some(b'\t') | Some(b'\r') | Some(b'\n')
        ) {
            search_start = after_tag_name;
            continue;
        }

        let content_start = start + markdown[start..].find('>')? + 1;
        let content_end = content_start + lower[content_start..].find("</h1>")?;
        let title = strip_html_tags(&markdown[content_start..content_end])
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        if !title.is_empty() {
            return Some(title);
        }

        search_start = content_end + 5;
    }

    None
}

fn strip_html_tags(input: &str) -> String {
    let mut output = String::with_capacity(input.len());
    let mut in_tag = false;

    for ch in input.chars() {
        match ch {
            '<' => in_tag = true,
            '>' if in_tag => in_tag = false,
            _ if !in_tag => output.push(ch),
            _ => {}
        }
    }

    output
}

/// Wall-clock time spent in each stage of one render workflow, plus the
/// workflow's total. Reported to stderr by the CLI's `--verbose` output.
/// Stages that do not run for a given invocation (`sanitize` under
/// `--unsafe-html`, `assemble` under `--bare`) report zero.
#[derive(Debug, Default)]
pub struct StageTimings {
    pub read: Duration,
    pub markdown: Duration,
    pub sanitize: Duration,
    pub assemble: Duration,
    pub write: Duration,
    /// Wall-clock time of the whole workflow, always at least the sum of
    /// the stages.
    pub total: Duration,
}

/// One render request for [`convert`]: a Markdown input, a destination, and
/// the render options. `verbose` is deliberately absent — diagnostics are
/// the caller's presentation concern, and [`ConvertOutcome::timings`]
/// carries everything a caller needs to print them.
#[derive(Debug)]
pub struct ConvertRequest<'a> {
    /// The Markdown source file.
    pub input: &'a Path,
    /// The HTML file to write; created when missing, overwritten when
    /// present.
    pub output: &'a Path,
    /// Emit only the HTML fragment (no `<html>`, `<head>`, `<body>`, no CSS).
    pub bare: bool,
    /// Preserve raw HTML from the Markdown source instead of sanitizing it.
    pub unsafe_html: bool,
    /// Write the output file readable only by the current user.
    pub private_output: bool,
    /// Custom CSS appended after mdo's default styling. Read from disk here
    /// and ignored under `bare`, because bare output emits no CSS.
    pub css_override: Option<&'a Path>,
}

/// What a successful [`convert`] wrote: the output file plus the workflow's
/// stage-by-stage timing record.
#[derive(Debug)]
pub struct ConvertOutcome {
    /// The output file that was written.
    pub output: PathBuf,
    /// Wall-clock timing record for the completed workflow.
    pub timings: StageTimings,
}

/// Why a [`convert`] workflow failed, typed per failure site with the
/// underlying `io::Error` and the path it concerns, so callers keep printing
/// their own messages instead of the library doing it for them.
#[derive(Debug)]
pub enum RenderError {
    /// Reading the Markdown input file failed.
    Read { path: PathBuf, source: io::Error },
    /// Reading the `--css` override file failed.
    ReadCssOverride { path: PathBuf, source: io::Error },
    /// Creating the output file's parent directory failed.
    CreateOutputDir { path: PathBuf, source: io::Error },
    /// Writing the rendered HTML file failed.
    Write { path: PathBuf, source: io::Error },
}

impl fmt::Display for RenderError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let (action, path, source) = match self {
            RenderError::Read { path, source } => ("failed to read", path, source),
            RenderError::ReadCssOverride { path, source } => {
                ("failed to read CSS override", path, source)
            }
            RenderError::CreateOutputDir { path, source } => ("failed to create", path, source),
            RenderError::Write { path, source } => ("failed to write", path, source),
        };
        write!(f, "{} {}: {}", action, path.display(), source)
    }
}

impl std::error::Error for RenderError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        Some(match self {
            RenderError::Read { source, .. }
            | RenderError::ReadCssOverride { source, .. }
            | RenderError::CreateOutputDir { source, .. }
            | RenderError::Write { source, .. } => source,
        })
    }
}

/// Render one Markdown file to HTML: the render pipeline's single deep
/// entry point.
///
/// The workflow: read the source (and any CSS override), render and splice
/// highlighting, sanitize (unless `unsafe_html`), assemble the page (unless
/// `bare`), create the output's parent directory when missing, then write
/// the file (O_NOFOLLOW, mode 0o600 under `private_output`). The workflow
/// prints nothing itself — success carries a [`ConvertOutcome`] with the
/// written file and timing record, failure a typed [`RenderError`] — so the
/// same workflow serves the CLI, the setup sample, and any other host, and
/// the generated HTML is byte-identical everywhere it is invoked from.
pub fn convert(request: ConvertRequest) -> Result<ConvertOutcome, RenderError> {
    let workflow_start = Instant::now();
    let mut timings = StageTimings::default();

    let stage_start = Instant::now();
    let markdown = fs::read_to_string(request.input).map_err(|source| RenderError::Read {
        path: request.input.to_path_buf(),
        source,
    })?;
    timings.read = stage_start.elapsed();

    let css_override = if request.bare {
        None
    } else {
        match request.css_override {
            Some(path) => {
                let stage_start = Instant::now();
                let css =
                    fs::read_to_string(path).map_err(|source| RenderError::ReadCssOverride {
                        path: path.to_path_buf(),
                        source,
                    })?;
                timings.read += stage_start.elapsed();
                Some(css)
            }
            None => None,
        }
    };

    // Same splice loop as `safe_markdown_body`, instrumented for the
    // outcome's timing record.
    let (body, highlight_css) = spliced_markdown_body(
        &markdown,
        |markdown, discriminator, plain_fences| {
            let stage_start = Instant::now();
            let rendered = markdown_to_html(markdown, discriminator, plain_fences);
            timings.markdown += stage_start.elapsed();
            rendered
        },
        |html| {
            if request.unsafe_html {
                html.to_string()
            } else {
                let sanitize_start = Instant::now();
                let sanitized = sanitize_html(html);
                timings.sanitize += sanitize_start.elapsed();
                sanitized
            }
        },
    );

    let final_html = if request.bare {
        body
    } else {
        let stage_start = Instant::now();
        let fallback = request
            .input
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("Document");
        let title = derive_title(&markdown, fallback);

        // Only inject <base href> when the output lives in a different
        // directory from the source — otherwise relative refs already
        // resolve correctly and a base tag would just add noise.
        let base_href = match (
            fs::canonicalize(request.input)
                .ok()
                .and_then(|p| p.parent().map(Path::to_path_buf)),
            request
                .output
                .parent()
                .and_then(|p| fs::canonicalize(p).ok()),
        ) {
            (Some(in_dir), Some(out_dir)) if in_dir != out_dir => dir_to_file_url(&in_dir),
            _ => None,
        };

        let wrapped = wrap_html5(
            &body,
            &title,
            base_href.as_deref(),
            css_override.as_deref(),
            highlight_css,
            source_modified_unix_secs(request.input),
        );
        timings.assemble = stage_start.elapsed();
        wrapped
    };

    let stage_start = Instant::now();
    if let Some(parent) = request.output.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent).map_err(|source| RenderError::CreateOutputDir {
                path: parent.to_path_buf(),
                source,
            })?;
        }
    }

    write_output_file(request.output, &final_html, request.private_output).map_err(|source| {
        RenderError::Write {
            path: request.output.to_path_buf(),
            source,
        }
    })?;
    timings.write = stage_start.elapsed();
    timings.total = workflow_start.elapsed();

    Ok(ConvertOutcome {
        output: request.output.to_path_buf(),
        timings,
    })
}

#[cfg(unix)]
fn write_output_file(output: &Path, contents: &str, private_output: bool) -> io::Result<()> {
    let mut options = OpenOptions::new();
    options
        .write(true)
        .create(true)
        .truncate(true)
        .custom_flags(libc::O_NOFOLLOW);

    if private_output {
        options.mode(0o600);
    }

    let mut file = options.open(output)?;
    file.write_all(contents.as_bytes())
}

#[cfg(not(unix))]
fn write_output_file(output: &Path, contents: &str, _private_output: bool) -> io::Result<()> {
    fs::write(output, contents)
}
